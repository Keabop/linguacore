// Writes src/data/storyIndex.ts: what the story list and the dashboard show of each static story,
// without its text, so those screens don't download every story. Run with `npm run content:index`
// after adding or changing stories; the content tests fail while the file is out of date.
import { writeFileSync } from 'node:fs';
import { storiesData } from '../src/data/stories';
import { storySummary } from '../src/data/storySummary';

const rows = storiesData.map(s => `    ${JSON.stringify(storySummary(s))},`).join('\n');
writeFileSync('src/data/storyIndex.ts', `// Generated by \`npm run content:index\` from the stories. Do not edit.
import type { StorySummary } from './storySummary';

export const storyIndex: StorySummary[] = [
${rows}
];
`);
console.log(`${storiesData.length} stories indexed`);
