// `npm run content:audio`: generates with Kokoro the audio that is missing, writes
// src/data/audio/manifest.ts and deletes the files no script or story uses any more.
// Needs Python 3.10 (`py -3.10`); scripts/audio/generate.py sets up its own venv and model.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { audioJobs } from '../src/data/audio/jobs';

const OUT = 'public/audio';
const CACHE = 'node_modules/.cache';
const TIMINGS = 'content/audio/timings.json';

mkdirSync(OUT, { recursive: true });
mkdirSync(CACHE, { recursive: true });
mkdirSync('content/audio', { recursive: true });

const jobs = audioJobs();
const timings: Record<string, number[]> = existsSync(TIMINGS) ? JSON.parse(readFileSync(TIMINGS, 'utf8')) : {};
const pending = jobs.filter(j => !existsSync(join(OUT, `${j.key}.ogg`)) || (j.kind === 'story' && !timings[j.key]));

if (pending.length) {
    const jobsFile = join(CACHE, 'audio-jobs.json');
    const resultFile = join(CACHE, 'audio-timings.json');
    writeFileSync(jobsFile, JSON.stringify(pending));
    console.log(`Generating ${pending.length} of ${jobs.length} recordings with Kokoro...`);
    execFileSync('py', ['-3.10', 'scripts/audio/generate.py', jobsFile, OUT, resultFile], { stdio: 'inherit' });
    Object.assign(timings, JSON.parse(readFileSync(resultFile, 'utf8')));
}

// Only what is still used stays: files and timings of changed scripts go away
const keys = new Set(jobs.map(j => j.key));
let removed = 0;
for (const file of readdirSync(OUT)) {
    if (!keys.has(file.replace(/\.ogg$/, ''))) {
        rmSync(join(OUT, file));
        removed++;
    }
}
const kept = Object.fromEntries(Object.entries(timings).filter(([k]) => keys.has(k)).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(TIMINGS, JSON.stringify(kept, null, 1) + '\n');

const entries = [...jobs].sort((a, b) => a.key.localeCompare(b.key)).map(j => {
    const starts = j.kind === 'story' ? `, sentences: [${kept[j.key].join(', ')}]` : '';
    return `    '${j.key}': { src: '/audio/${j.key}.ogg'${starts} },`;
});
writeFileSync('src/data/audio/manifest.ts', `// Generated by \`npm run content:audio\`. Do not edit.
import type { AudioEntry } from '../../lib/audioKey';

export const AUDIO_MANIFEST: Record<string, AudioEntry> = {
${entries.join('\n')}
};
`);

let bytes = 0;
for (const file of readdirSync(OUT)) bytes += readFileSync(join(OUT, file)).length;
console.log(`${jobs.length} recordings (${(bytes / 1048576).toFixed(1)} MB), ${removed} removed`);
