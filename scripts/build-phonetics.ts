// Writes src/data/vocabulary/phonetics.ts: the IPA of every vocabulary card, from CMUdict
// (content/reference/pronunciations.json). Run with `npm run content:phonetics` after adding
// or changing cards; the content tests fail while the file is out of date.
import { writeFileSync } from 'node:fs';
import pronunciations from '../content/reference/pronunciations.json';
import { a1Vocabulary } from '../src/data/vocabulary/a1';
import { a2Vocabulary } from '../src/data/vocabulary/a2';
import { b1Vocabulary } from '../src/data/vocabulary/b1';
import { b2Vocabulary } from '../src/data/vocabulary/b2';
import { ipaOf } from '../src/data/pronunciation';

const ids = [...a1Vocabulary, ...a2Vocabulary, ...b1Vocabulary, ...b2Vocabulary].map(v => v.id);
const entries: [string, string][] = [];
const missing: string[] = [];
for (const id of ids) {
    const ipa = ipaOf(id, pronunciations);
    if (ipa) entries.push([id, ipa]);
    else missing.push(id);
}

const body = entries.map(([id, ipa]) => `    ${JSON.stringify(id)}: ${JSON.stringify(ipa)},`).join('\n');
writeFileSync('src/data/vocabulary/phonetics.ts', `// Generated by \`npm run content:phonetics\` from CMUdict (content/reference/). Do not edit:
// homographs and missing words are set in src/data/pronunciation.ts.
export const phonetics: Record<string, string> = {
${body}
};
`);
console.log(`${entries.length} transcriptions written`);
if (missing.length) console.log(`Missing from CMUdict (add them to MANUAL_IPA): ${missing.join(', ')}`);
