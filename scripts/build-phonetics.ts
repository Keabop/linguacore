// Writes, from CMUdict (content/reference/pronunciations.json):
// - src/data/vocabulary/phonetics/{a1,a2,b1,b2}.ts: the IPA of each level's cards, so a level's deck
//   loads with only its own transcriptions;
// - src/data/vocabulary/phonetics.ts: all of them, for tests and scripts;
// - src/data/vocabulary/wordLevels.ts: the level of every card id, so a screen knows which decks to
//   download for the words it shows.
// Run with `npm run content:phonetics` after adding or changing cards; the content tests fail while
// these files are out of date.
import { mkdirSync, writeFileSync } from 'node:fs';
import pronunciations from '../content/reference/pronunciations.json';
import { a1Vocabulary } from '../src/data/vocabulary/a1';
import { a2Vocabulary } from '../src/data/vocabulary/a2';
import { b1Vocabulary } from '../src/data/vocabulary/b1';
import { b2Vocabulary } from '../src/data/vocabulary/b2';
import { ipaOf } from '../src/data/pronunciation';

const HEADER = `// Generated by \`npm run content:phonetics\` from CMUdict (content/reference/). Do not edit:
// homographs and missing words are set in src/data/pronunciation.ts.`;
const decks = { a1: a1Vocabulary, a2: a2Vocabulary, b1: b1Vocabulary, b2: b2Vocabulary };

mkdirSync('src/data/vocabulary/phonetics', { recursive: true });
const missing: string[] = [];
let written = 0;
for (const [level, deck] of Object.entries(decks)) {
    const entries: [string, string][] = [];
    for (const { id } of deck) {
        const ipa = ipaOf(id, pronunciations);
        if (ipa) entries.push([id, ipa]);
        else missing.push(id);
    }
    written += entries.length;
    const body = entries.map(([id, ipa]) => `    ${JSON.stringify(id)}: ${JSON.stringify(ipa)},`).join('\n');
    writeFileSync(`src/data/vocabulary/phonetics/${level}.ts`, `${HEADER}
export const ${level}Phonetics: Record<string, string> = {
${body}
};
`);
}

writeFileSync('src/data/vocabulary/phonetics.ts', `${HEADER}
import { a1Phonetics } from './phonetics/a1';
import { a2Phonetics } from './phonetics/a2';
import { b1Phonetics } from './phonetics/b1';
import { b2Phonetics } from './phonetics/b2';

export const phonetics: Record<string, string> = { ...a1Phonetics, ...a2Phonetics, ...b1Phonetics, ...b2Phonetics };
`);

// One line of ids per level keeps the index small: the app builds the lookup when it loads
const lines = Object.entries(decks).map(([level, deck]) => `    ${level.toUpperCase()}: ${JSON.stringify(deck.map(v => v.id).join('|'))},`);
writeFileSync('src/data/vocabulary/wordLevels.ts', `// Generated by \`npm run content:phonetics\` from the decks. Do not edit.
import type { ContentLevel } from '../levels';

/** The ids of each level's cards, separated by "|". */
export const WORD_IDS: Record<ContentLevel, string> = {
${lines.join('\n')}
};
`);

console.log(`${written} transcriptions written`);
if (missing.length) console.log(`Missing from CMUdict (add them to MANUAL_IPA): ${missing.join(', ')}`);
